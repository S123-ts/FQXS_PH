-- 判定历史（append-only）：novel_ai_verdict 的唯一键是 (book_id, engine, model)，
-- 同一型号重复判定会覆盖旧行，「这本书被 GLM 判过几次、每次什么结论」就此丢失。
-- 详情面板要回答的正是这个问题，所以每次落结论时另记一条流水。
--
-- kind 区分动作：sweep=整本初筛 / verify=逐章校验一步 / progress=逐章已达上限只推进度
CREATE TABLE IF NOT EXISTS novel_ai_verdict_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id VARCHAR(50) NOT NULL,
    engine VARCHAR(40) NOT NULL,
    model VARCHAR(80) DEFAULT 'legacy' NOT NULL,
    ai_flag TINYINT NOT NULL,
    ai_score DECIMAL(5,2),
    reason VARCHAR(200),
    prompt_id VARCHAR(24),
    sample_mode VARCHAR(24),
    sample_span VARCHAR(40),
    chapters_checked INT DEFAULT 0 NOT NULL,
    kind VARCHAR(16) NOT NULL,
    checked_time TIMESTAMP NOT NULL
);
-- 查询恒定按「某本书的全部轮次、时间倒序」，索引照它建
CREATE INDEX IF NOT EXISTS idx_verdict_log_book_time ON novel_ai_verdict_log (book_id, checked_time);
