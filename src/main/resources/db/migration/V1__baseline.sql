-- H2 表结构基线（Flyway V1，2026-10-22 从 db/schema-h2.sql 固化）。
-- 已有库由 baseline-on-migrate 直接标到 V1，不重放本脚本；新库按顺序执行。
-- 后续变更另建 V2__xxx.sql，不要改本文件（checksum 会失效）。
-- rank 故意不加引号：H2 会把不加引号的标识符存成大写，和 Hibernate 生成的 SQL 对得上。
-- book_id 不设任何唯一约束：同书可同挂多分类榜/双榜单，唯一性交给下面的三列组合键。
CREATE TABLE IF NOT EXISTS novel_rank (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rank VARCHAR(50) NOT NULL,
    book_id VARCHAR(50),
    title VARCHAR(200) NOT NULL,
    author VARCHAR(100),
    description VARCHAR(20000),
    status VARCHAR(20),
    read_count VARCHAR(20),
    read_count_raw BIGINT,
    last_chapter VARCHAR(200),
    update_time VARCHAR(50),
    thumb_uri VARCHAR(500),
    category_name VARCHAR(50),
    word_count VARCHAR(20),
    create_time TIMESTAMP,
    update_time_db TIMESTAMP,
    is_blocked BOOLEAN DEFAULT FALSE NOT NULL,
    blocked_time TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_category ON novel_rank (category_name);

-- 同一本书可同时上多个分类榜（科幻末世/游戏体育/悬疑脑洞男女频共用 category_id），
-- 唯一性从 book_id 全局唯一改为 (category_code, book_id) 组合唯一。
-- 老库升级：先加列（历史行 gender 由 DEFAULT 1 落成男频），再换约束；
-- NULL book_id 行在唯一约束里互不冲突（H2 把 NULL 视为互异）。
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS category_code VARCHAR(50);
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS gender TINYINT DEFAULT 1 NOT NULL;
CREATE INDEX IF NOT EXISTS idx_category_code ON novel_rank (category_code);

-- 榜单类型分区：阅读榜(read)/新书榜(new)各自成快照，切榜直接读库不用重抓。
-- 历史行全部是在阅读榜（默认 rankMold=2）下抓的，DEFAULT 'read' 恰好落对区；
-- 旧的两列唯一键在这里换轨成三列，任何一步中断都可重放。
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS rank_type VARCHAR(10) DEFAULT 'read' NOT NULL;
-- 老库遗留的 book_id 全局唯一键（早于 category_code 分榜的时代）：必须无条件摘除，
-- 否则同书跨分类/跨榜单的第二行插入会直接撞键。新库上 CREATE TABLE 已不再声明它，此句是空操作。
ALTER TABLE novel_rank DROP CONSTRAINT IF EXISTS uk_novel_rank_book_id;
ALTER TABLE novel_rank DROP CONSTRAINT IF EXISTS uk_novel_rank_cat_book;
ALTER TABLE novel_rank ADD CONSTRAINT IF NOT EXISTS uk_novel_rank_cat_type_book
    UNIQUE (category_code, rank_type, book_id);

-- AI 文判定结果：免费引擎（GLM）跑整书，朱雀引擎逐章推进、命中即停。
-- 两套结果分开存：免费引擎覆盖全部书，朱雀只覆盖用户手动点过的书，互不覆盖。
-- ai_flag/zq_flag 语义：0=未判 1=非 AI 2=AI 3=疑似 AI（仅 ai_flag 有 3）
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS ai_flag TINYINT DEFAULT 0 NOT NULL;
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS ai_score DECIMAL(5,2);
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS ai_engine VARCHAR(30);
-- 引擎注册表允许最长 40 位 id：主表列宽跟着放开，否则自建引擎结论写主表会超长
ALTER TABLE novel_rank ALTER COLUMN ai_engine SET DATA TYPE VARCHAR(40);
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS ai_checked_time TIMESTAMP;
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS zq_flag TINYINT DEFAULT 0 NOT NULL;
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS zq_score DECIMAL(5,2);
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS zq_chapters_checked INT DEFAULT 0 NOT NULL;
ALTER TABLE novel_rank ADD COLUMN IF NOT EXISTS zq_checked_time TIMESTAMP;
CREATE INDEX IF NOT EXISTS idx_ai_flag ON novel_rank (ai_flag);

-- 各引擎判定明细：一个引擎的一个型号对一本书只保留最新一条。
-- 主表 ai_* 是综合结论（最新免费判定，朱雀命中时覆盖），逐引擎结论在这里可追溯。
-- model 记录产出该结论的型号：切型号后旧结论不再被幂等守卫复用（否则付费型号会一直吃免费结论）。
CREATE TABLE IF NOT EXISTS novel_ai_verdict (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id VARCHAR(50) NOT NULL,
    engine VARCHAR(40) NOT NULL,
    model VARCHAR(80) DEFAULT 'legacy' NOT NULL,
    ai_flag TINYINT NOT NULL,
    ai_score DECIMAL(5,2),
    reason VARCHAR(200),
    checked_time TIMESTAMP
);
ALTER TABLE novel_ai_verdict ADD COLUMN IF NOT EXISTS model VARCHAR(80) DEFAULT 'legacy' NOT NULL;
ALTER TABLE novel_ai_verdict DROP CONSTRAINT IF EXISTS uk_ai_verdict_book_engine;
ALTER TABLE novel_ai_verdict ADD CONSTRAINT IF NOT EXISTS uk_ai_verdict_book_engine_model
    UNIQUE (book_id, engine, model);
CREATE INDEX IF NOT EXISTS idx_ai_verdict_book ON novel_ai_verdict (book_id);

-- 逐章校验的推进进度：每个 (book_id, engine) 一行独立记录，避免多引擎共用一组进度
ALTER TABLE novel_ai_verdict ADD COLUMN IF NOT EXISTS chapters_checked INT DEFAULT 0 NOT NULL;

-- AI 引擎注册表：内置三家免费渠道 + 用户自带的任意 OpenAI 兼容端点。
-- api_key 故意不在这里：密钥仍只写 data/ai-keys.properties（data/ 已 gitignore），
-- 避免 H2 文件被复制或导出时连带泄露。protocol=classify 是朱雀私有格式，不并入通用分支。
CREATE TABLE IF NOT EXISTS ai_engine (
    id VARCHAR(40) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    base_url VARCHAR(300) NOT NULL,
    model VARCHAR(80) NOT NULL,
    models_csv VARCHAR(2000),
    -- 勾选的型号池（逗号分隔）：判定时在池内随机取一个；为空则退回 model 单值
    model_pool VARCHAR(600),
    protocol VARCHAR(20) DEFAULT 'openai_chat' NOT NULL,
    builtin BOOLEAN DEFAULT FALSE NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    auto_ban BOOLEAN DEFAULT TRUE NOT NULL,
    priority INT DEFAULT 100 NOT NULL,
    remark VARCHAR(200)
);
-- 已建库的升级补列：型号池（逗号分隔，判定时随机取一个）
ALTER TABLE ai_engine ADD COLUMN IF NOT EXISTS model_pool VARCHAR(600);

-- 运行时配置（rank_type / display_categories），由 StartupDataInitializer 播种、ConfigService 缓存
CREATE TABLE IF NOT EXISTS app_config (
    cfg_key VARCHAR(100) PRIMARY KEY,
    cfg_value VARCHAR(4000) NOT NULL,
    update_time_db TIMESTAMP
);

-- AI 判定提示词库：一条 system prompt 一个变体，判定时在启用的池内随机取一条。
-- 随机而不是固定一条，是为了让结论不被单一提示词的特征盲区带偏：
-- 不同变体抓的特征面不同（P1 看结构、P2 分项打分、P7 看中文八股指纹、P8 看语法毛刺），
-- 换着用相当于把多个判据视角摊到全库，而不是全库共用一套盲区。
-- poolable=0 的变体（需锚定样本 / 假设单章输入 / 不产出概率）只入库不随机，供手动调用。
CREATE TABLE IF NOT EXISTS ai_prompt (
    id VARCHAR(24) PRIMARY KEY,
    name VARCHAR(60) NOT NULL,
    -- system prompt 全文；判定请求只把它放在 system 位，正文永不进这一列
    content VARCHAR(4000) NOT NULL,
    -- 来源出处：自建还是引自哪个开源方案，便于日后溯源与替换
    origin VARCHAR(200),
    builtin BOOLEAN DEFAULT FALSE NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL,
    -- 是否参与随机池
    poolable BOOLEAN DEFAULT TRUE NOT NULL,
    -- 随机权重：调大即提高中签率，用于让更稳的变体多承担一些量
    weight INT DEFAULT 100 NOT NULL,
    sort_order INT DEFAULT 100 NOT NULL,
    remark VARCHAR(200)
);
-- 已建库的升级补列（本表随版本新增，老库直接补）
CREATE INDEX IF NOT EXISTS idx_ai_prompt_pool ON ai_prompt (enabled, poolable);

-- 判定明细记录本次用的提示词：同一本书换提示词不会自动重判（幂等键仍是 book+engine+model），
-- 但结论出自哪个变体必须可追溯，否则无法事后比较各变体的分歧与准确率。
ALTER TABLE novel_ai_verdict ADD COLUMN IF NOT EXISTS prompt_id VARCHAR(24);

-- AI 调用用量明细：每次模型调用一行，查询时按日聚合（不预聚合，避免并发累加的锁）
CREATE TABLE IF NOT EXISTS ai_usage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usage_time TIMESTAMP NOT NULL,
    engine VARCHAR(40) NOT NULL,
    model VARCHAR(80) DEFAULT '' NOT NULL,
    prompt_id VARCHAR(24) DEFAULT '' NOT NULL,
    prompt_tokens INT DEFAULT 0 NOT NULL,
    completion_tokens INT DEFAULT 0 NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ai_usage_time ON ai_usage (usage_time);
