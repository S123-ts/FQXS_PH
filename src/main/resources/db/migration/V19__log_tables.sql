-- 日志落库：三类日志各一张表，互不干扰，且都带 book_id。
--
-- 为什么要落库：文件日志（log/fqxs.log）只能 grep，跨天要翻多个文件、按接口/线路聚合得写脚本。
-- 落库后「某个第三方线路今天失败多少次」「某个接口平均耗时」都能一条 SQL 回答。
--
-- 为什么每张表都有 book_id：日志的生命周期跟随书——书还在榜上就留着它的日志，
-- 书掉榜或被删就把它的日志一起清掉（见 LogRetentionJob）。没有 book_id 的系统级日志
-- （启动、定时任务）按天数兜底清理。
--
-- 写入路径统一走异步批量（LogBuffer 有界队列 + LogDbWriter 每 250ms 落一次），
-- 表结构因此刻意扁平：只有定长/截断过的字符串，没有外键、没有 JSON 列，
-- 保证单条 insert 足够便宜。message / exception 的超长部分在应用侧截断（见 AppLogEntry）。

-- ① 全量程序日志：logback root 的每一条都镜像一份（文件仍然保留，这里给检索用）
CREATE TABLE IF NOT EXISTS app_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    log_time TIMESTAMP NOT NULL,
    level VARCHAR(8) NOT NULL,
    thread VARCHAR(80),
    logger VARCHAR(160),
    book_id VARCHAR(50),
    message VARCHAR(2000),
    exception VARCHAR(4000),
    created_time TIMESTAMP NOT NULL
);
-- 查询恒定是「某段时间 + 某级别」，两个索引分别覆盖「按时间翻」与「只看 ERROR」
CREATE INDEX IF NOT EXISTS idx_app_log_time ON app_log (log_time);
CREATE INDEX IF NOT EXISTS idx_app_log_level_time ON app_log (level, log_time);
-- 「这本书出过什么错」= 按 book_id 查，单列索引
CREATE INDEX IF NOT EXISTS idx_app_log_book_time ON app_log (book_id, log_time);

-- ② API 日志：direction 区分两个方向，避免「谁调了我」和「我调了上游」混在一张表里分不清
--    IN  = 本系统对外接口（/api/**）的一次请求，含被登录门挡下的 401
--    OUT = 打向番茄官方接口的出站调用（榜单 / 目录 / 正文）
CREATE TABLE IF NOT EXISTS api_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    direction VARCHAR(8) NOT NULL,
    api_time TIMESTAMP NOT NULL,
    method VARCHAR(8),
    target VARCHAR(500),
    query VARCHAR(1000),
    book_id VARCHAR(50),
    status INT,
    duration_ms INT,
    bytes INT,
    client_ip VARCHAR(64),
    username VARCHAR(64),
    user_agent VARCHAR(300),
    outcome VARCHAR(16),
    error VARCHAR(1000),
    created_time TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_api_log_time ON api_log (api_time);
CREATE INDEX IF NOT EXISTS idx_api_log_direction_time ON api_log (direction, api_time);
CREATE INDEX IF NOT EXISTS idx_api_log_book_time ON api_log (book_id, api_time);

-- ③ 第三方抽取日志：ThirdPartySources 每尝试一条线路记一行（失败换线时会有多行）
--    line 是线路 base url，path 是 /info /content /catalog，param_value 是 book_id / item_id。
--    book_id 在 /content 这类只有 item_id 的场景由调用链的 MDC 补（见 BookLogContext）。
--    outcome：OK / HTTP_ERROR / EMPTY / IO_ERROR / PARSE_ERROR / ITEM_UNAVAILABLE
CREATE TABLE IF NOT EXISTS third_party_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_time TIMESTAMP NOT NULL,
    line VARCHAR(200),
    path VARCHAR(40),
    scene VARCHAR(40),
    param_name VARCHAR(40),
    param_value VARCHAR(80),
    book_id VARCHAR(50),
    status INT,
    bytes INT,
    duration_ms INT,
    outcome VARCHAR(16) NOT NULL,
    error VARCHAR(1000),
    created_time TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_third_party_log_time ON third_party_log (request_time);
-- 「这条线路最近挂了没」是最高频的查询，索引按它建
CREATE INDEX IF NOT EXISTS idx_third_party_log_line_time ON third_party_log (line, request_time);
CREATE INDEX IF NOT EXISTS idx_third_party_log_book_time ON third_party_log (book_id, request_time);

-- 清理任务要按「这本书还在不在榜上」判断，novel_rank.book_id 必须有单列索引，
-- 否则 NOT EXISTS 子查询会退化成全表扫。V1 里只有 (category_code, book_id) 复合唯一键，首列不是 book_id。
CREATE INDEX IF NOT EXISTS idx_novel_rank_book_id ON novel_rank (book_id);
