-- 章节正文缓存：只存「官方前 10 章」这一档。
-- 为什么落库：默认取样就是前 10 章，同一本书换引擎重判、翻页回看、批量初筛都会重复抓同一批章节；
-- 正文发布后不会变，存下来后第二次起零上游请求，也不再和 AI 判定抢 800ms 节拍。
--
-- 为什么不存第三方章节：那条线路跑在别人的共享云手机上，正文可能被替换或失效，
-- 缓存下来反而会把一次错误固化（详见《AI取样与交互改造方案》§3.1）。
CREATE TABLE IF NOT EXISTS novel_chapter (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id        VARCHAR(50)   NOT NULL,
    item_id        VARCHAR(50)   NOT NULL,
    chapter_index  INT           NOT NULL,
    chapter_title  VARCHAR(200),
    -- 单章实测 2500 字上下，2 万字足够；与 novel_rank.description 同规格，H2/MySQL 都能跑
    content        VARCHAR(20000) NOT NULL,
    char_count     INT           NOT NULL,
    -- 解码后仍残留的私用区字符数：映射表过期的唯一可观察信号
    pua_unresolved INT DEFAULT 0 NOT NULL,
    source         VARCHAR(16) DEFAULT 'official' NOT NULL,
    fetched_time   TIMESTAMP     NOT NULL,
    updated_time   TIMESTAMP     NOT NULL
);

-- 章节 ID 全局唯一，跨书不会撞
CREATE UNIQUE INDEX IF NOT EXISTS uk_novel_chapter_item ON novel_chapter (item_id);
-- 按书回放/统计用
CREATE INDEX IF NOT EXISTS idx_novel_chapter_book ON novel_chapter (book_id, chapter_index);
