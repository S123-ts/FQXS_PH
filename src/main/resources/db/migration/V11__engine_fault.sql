-- 调用失败留证：模型不行时要能回答「哪一次、哪个引擎哪个型号、上游到底回了什么」。
-- 成功调用的用量在 ai_usage，失败事实单独一张表，不与判定结论混写。
CREATE TABLE IF NOT EXISTS ai_engine_fault (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    engine VARCHAR(40) NOT NULL,
    model VARCHAR(80),
    -- kind：auth(401/403) / rate(429) / server(5xx) / network(超时连不上) / empty(空响应) / parse(回的东西解析不出概率)
    kind VARCHAR(20) NOT NULL,
    http_status INT,
    reason VARCHAR(300) NOT NULL,
    -- 上游返回片段：入库前已截断；只存响应体，请求头里的 Bearer 密钥永不进这一列
    response_excerpt VARCHAR(1000),
    book_id VARCHAR(50),
    occurred_time TIMESTAMP NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_fault_engine_time ON ai_engine_fault (engine, occurred_time);
CREATE INDEX IF NOT EXISTS idx_fault_time ON ai_engine_fault (occurred_time);

-- 连续失败后的自动停用：到期时间落库而不是放内存，重启才不会把停用状态洗掉。
-- consecutive_failures 只在成功判定后清零，避免"零星失败"就把一个引擎摁死两天。
ALTER TABLE ai_engine ADD COLUMN IF NOT EXISTS disable_until TIMESTAMP;
ALTER TABLE ai_engine ADD COLUMN IF NOT EXISTS disable_reason VARCHAR(300);
ALTER TABLE ai_engine ADD COLUMN IF NOT EXISTS consecutive_failures INT DEFAULT 0 NOT NULL;
